// Two theme rules that were checked by hand (ADR 14, docs/themes/README.md):
//   1. apps/desktop/src/lib/theme/tokens.css is the active theme's token block, copied verbatim.
//   2. No literal colour, font, radius or duration appears in apps/desktop/src outside tokens.css.
// Run from anywhere: node tools/theme-check/check.mjs
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (path) => readFileSync(join(repo, path), "utf8");
const problems = [];

// 1. The token block.
const readme = read("docs/themes/README.md");
const active = /## Active theme\s+\*\*`([a-z0-9-]+)`\*\*/.exec(readme)?.[1];
if (!active) {
  console.error("docs/themes/README.md names no active theme under `## Active theme`.");
  process.exit(1);
}
const spec = read(`docs/themes/${active}.md`);
const block = /## Tokens[\s\S]*?```css\n([\s\S]*?)```/.exec(spec)?.[1];
if (!block) {
  console.error(`docs/themes/${active}.md has no css block under \`## Tokens\`.`);
  process.exit(1);
}
const tokensPath = "apps/desktop/src/lib/theme/tokens.css";
const [header, ...body] = read(tokensPath).split("\n");
if (!header.startsWith("/* Generated by /apply-theme")) {
  problems.push(`${tokensPath} lost its "Generated by /apply-theme" header line.`);
}
if (body.join("\n").trim() !== block.trim()) {
  problems.push(
    `${tokensPath} is not the token block of docs/themes/${active}.md. ` +
      "Edit the theme and regenerate it with /apply-theme; never edit tokens.css by hand.",
  );
}

// 2. Literal values. The pattern is the one /apply-theme uses.
const literal =
  /#[0-9a-fA-F]{3,8}([^0-9a-zA-Z_-]|$)|rgba?\(|hsla?\(|[0-9]m?s([^0-9a-zA-Z_-]|$)|font-family:\s*[^v\s]|border-radius:\s*[0-9]/;

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return files(path);
    return /\.(svelte|css)$/.test(name) ? [path] : [];
  });
}

for (const path of files(join(repo, "apps/desktop/src"))) {
  const name = relative(repo, path);
  if (name === tokensPath) continue;
  readFileSync(path, "utf8")
    .split("\n")
    .forEach((line, index) => {
      if (literal.test(line)) problems.push(`${name}:${index + 1}: literal value: ${line.trim()}`);
    });
}

if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log(`Theme "${active}": tokens.css matches the spec and src has no literal values.`);
